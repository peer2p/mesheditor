const fs = require('fs');
const path = require('path');
const ejs = require('ejs');

const rootDir = path.resolve(__dirname, '..');
const editorToolsDir = path.resolve(rootDir, 'src/tools/editor');
const mesheditorEjsPath = path.resolve(rootDir, 'src/mesheditor.ejs');
const toolViewsTsPath = path.resolve(editorToolsDir, 'toolViews.ts');
const templateTsPath = path.resolve(rootDir, 'src/template.ts');

const TOOLS = [
  { className: 'OutlinerEditorTool', file: 'OutlinerEditorTool.ejs', id: 'dialog-outliner' },
  { className: 'CreatePrimitiveEditorTool', file: 'CreatePrimitiveEditorTool.ejs', id: 'dialog-create-primitive' },
  { className: 'CSGEditorTool', file: 'CSGEditorTool.ejs', id: 'dialog-csg' },
  { className: 'FacetEditorTool', file: 'FacetEditorTool.ejs', id: 'dialog-facet' },
  { className: 'SculptEditorTool', file: 'SculptEditorTool.ejs', id: 'dialog-sculpt' },
  { className: 'VoxelPainterEditorTool', file: 'VoxelPainterEditorTool.ejs', id: 'dialog-voxel-painter' },
  { className: 'PathExtrusionEditorTool', file: 'PathExtrusionEditorTool.ejs', id: 'dialog-path-extrusion' },
  { className: 'AIAgentEditorTool', file: 'AIAgentEditorTool.ejs', id: 'dialog-ai-agent' },
  { className: 'MeshPropertiesEditorTool', file: 'MeshPropertiesEditorTool.ejs', id: 'dialog-mesh' },
  { className: 'MaterialEditorTool', file: 'MaterialEditorTool.ejs', id: 'dialog-material' },
  { className: 'UVUnwrapEditorTool', file: 'UVUnwrapEditorTool.ejs', id: 'dialog-uv-unwrap' },
  { className: 'BakingEditorTool', file: 'BakingEditorTool.ejs', id: 'dialog-baking' },
  { className: 'TextureOptimizerEditorTool', file: 'TextureOptimizerEditorTool.ejs', id: 'dialog-textures' },
  { className: 'CompressModelEditorTool', file: 'CompressModelEditorTool.ejs', id: 'dialog-compress-model' },
  { className: 'SceneEnvironmentEditorTool', file: 'SceneEnvironmentEditorTool.ejs', id: 'dialog-scene' },
  { className: 'AnimationPlayerEditorTool', file: 'AnimationPlayerEditorTool.ejs', id: 'dialog-anim' },
  { className: 'RiggingEditorTool', file: 'RiggingEditorTool.ejs', id: 'dialog-rigging' },
];

function syncTemplates() {
  const toolViews = {};

  for (const tool of TOOLS) {
    const ejsPath = path.join(editorToolsDir, tool.file);
    if (!fs.existsSync(ejsPath)) {
      console.warn(`[sync-templates] Warning: View file not found: ${ejsPath}`);
      continue;
    }
    const content = fs.readFileSync(ejsPath, 'utf8').trim();
    toolViews[tool.className] = content;
    toolViews[tool.id] = content;
  }

  // 1. Generate src/tools/editor/toolViews.ts
  const toolViewsTsContent = `/**
 * Auto-generated tool view HTML templates.
 * Generated from src/tools/editor/*.ejs view templates.
 * Do not edit this file directly; edit the corresponding .ejs files or run 'node scripts/sync-templates.js'.
 */
export const TOOL_VIEWS: Record<string, string> = ${JSON.stringify(toolViews, null, 2)};

/**
 * Retrieves the compiled HTML view template for a specific tool class or dialog ID.
 */
export function getToolViewTemplate(identifier: string): string {
  return TOOL_VIEWS[identifier] || '';
}
`;
  fs.writeFileSync(toolViewsTsPath, toolViewsTsContent, 'utf8');

  // 2. Render src/mesheditor.ejs to populate src/template.ts
  const rawEjs = fs.readFileSync(mesheditorEjsPath, 'utf8');
  const renderedHtml = ejs.render(
    rawEjs,
    {
      htmlWebpackPlugin: {
        options: {
          title: 'Mesh Editor',
        },
      },
    },
    { filename: mesheditorEjsPath }
  );

  // Extract the inner content of <div id="app-container">...</div>
  const appContainerMatch = renderedHtml.match(/<div id="app-container"[^>]*>([\s\S]*?)<\/div>\s*<\/body>/);
  if (!appContainerMatch) {
    console.error('[sync-templates] Error: Could not locate #app-container in rendered mesheditor.ejs');
    return;
  }

  const appContainerInnerHtml = appContainerMatch[1];

  const templateTsContent = `/**
 * Initial empty state markup for the AI Chat log.
 * Single source of truth for both the initial UI rendering and chat resets.
 */
export const AI_CHAT_EMPTY_HTML: string = \`
              <div class="ai-chat-empty">
                <strong>Text / Image to 3D Mesh & Update</strong><br />
                Describe a 3D object, attach a reference image, or select a mesh in the scene to modify it with AI.
              </div>
\`.trim();

/**
 * Generates the inner HTML structure for the Mesh Editor UI.
 * Compiled from src/mesheditor.ejs and decentralized tool views (src/tools/editor/*.ejs).
 * Used when mounting the editor programmatically into a container element
 * or inside the <mesh-editor> Web Component.
 */
export function getMeshEditorTemplate(): string {
  return ${JSON.stringify(appContainerInnerHtml)};
}
`;

  fs.writeFileSync(templateTsPath, templateTsContent, 'utf8');
  console.log(`[sync-templates] Synced ${TOOLS.length} tool views and compiled src/template.ts`);
}

syncTemplates();

module.exports = { syncTemplates };

